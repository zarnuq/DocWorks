"""Generate src/domain/pptx/preset-shapes.ts from presetShapeDefinitions.xml
(the DrawingML preset geometry definitions from ECMA-376 Part 1, as shipped
e.g. in LibreOffice oox/source/drawingml/customshapes/).

Usage: python scripts/make_preset_shapes.py <presetShapeDefinitions.xml>

Each preset becomes one string of "~"-separated sections, evaluated by
src/domain/pptx/geometry.ts:
  av ~ gd ~ rect ~ cxn ~ ah ~ paths
  av, gd: "name=fmla" joined by ";"  (gdLst names are shortened to $0, $1...)
  rect:   "l t r b" ("" = whole shape)
  cxn:    "ang x y" joined by ";"
  ah:     "refX,minX,maxX,refY,minY,maxY,x,y" joined by ";"
  paths:  joined by "|"; each is "w,h,fill,stroke" then ";"-joined commands
          "M x y" | "L x y" | "A wR hR stAng swAng" | "C x1 y1 x2 y2 x y" | "Q x1 y1 x y" | "Z"
"""
import json
import os
import sys
import xml.etree.ElementTree as ET

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"


def local(el):
    return el.tag.split("}")[-1]


def child(el, name):
    return next((c for c in el if local(c) == name), None)


def gds(lst):
    return [f"{g.get('name')}={g.get('fmla')}" for g in lst] if lst is not None else []


def path_cmds(path):
    out = []
    for c in path:
        pts = [f"{p.get('x')} {p.get('y')}" for p in c if local(p) == "pt"]
        n = local(c)
        if n == "moveTo":
            out.append("M " + pts[0])
        elif n == "lnTo":
            out.append("L " + pts[0])
        elif n == "cubicBezTo":
            out.append("C " + " ".join(pts))
        elif n == "quadBezTo":
            out.append("Q " + " ".join(pts))
        elif n == "arcTo":
            out.append(f"A {c.get('wR')} {c.get('hR')} {c.get('stAng')} {c.get('swAng')}")
        elif n == "close":
            out.append("Z")
    return out


def main(src):
    root = ET.parse(src).getroot()
    presets = {}
    for shape in root:
        rec = {}
        av, gd = gds(child(shape, "avLst")), gds(child(shape, "gdLst"))
        if av:
            rec["av"] = av
        if gd:
            rec["gd"] = gd
        rect = child(shape, "rect")
        if rect is not None and [rect.get(k) for k in "ltrb"] != ["l", "t", "r", "b"]:
            rec["rect"] = [rect.get(k) for k in "ltrb"]
        cxn = child(shape, "cxnLst")
        if cxn is not None:
            rec["cxn"] = [[c.get("ang"), child(c, "pos").get("x"), child(c, "pos").get("y")] for c in cxn]
        ah = child(shape, "ahLst")
        if ah is not None:
            rec["ah"] = [
                [h.get(k) or "" for k in ("gdRefX", "minX", "maxX", "gdRefY", "minY", "maxY")] + [child(h, "pos").get("x"), child(h, "pos").get("y")]
                for h in ah
                if local(h) == "ahXY"
            ]
            if not rec["ah"]:
                del rec["ah"]
        paths = []
        for p in child(shape, "pathLst"):
            attrs = ",".join([p.get("w", ""), p.get("h", ""), p.get("fill", ""), p.get("stroke", "")]).rstrip(",")
            paths.append([attrs] + path_cmds(p))
        rec["paths"] = paths
        presets[local(shape)] = rec

    encoded = {}
    for name, rec in presets.items():
        short = {g.split("=", 1)[0]: f"${i}" for i, g in enumerate(rec.get("gd", []))}
        sub = lambda text: " ".join(short.get(t, t) for t in text.split(" "))
        gd = [f"{short[g.split('=', 1)[0]]}={sub(g.split('=', 1)[1])}" for g in rec.get("gd", [])]
        av = [f"{g.split('=', 1)[0]}={sub(g.split('=', 1)[1])}" for g in rec.get("av", [])]
        rect = sub(" ".join(rec["rect"])) if "rect" in rec else ""
        cxn = ";".join(sub(" ".join(c)) for c in rec.get("cxn", []))
        ah = ";".join(",".join(short.get(v, v) for v in h) for h in rec.get("ah", []))
        paths = "|".join(";".join([p[0]] + [sub(c) for c in p[1:]]) for p in rec["paths"])
        encoded[name] = "~".join([";".join(av), ";".join(gd), rect, cxn, ah, paths])

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "domain", "pptx", "preset-shapes.ts")
    with open(out, "w") as f:
        f.write("// Generated by scripts/make_preset_shapes.py from the ECMA-376 preset shape definitions - do not edit.\n")
        f.write("export const PRESETS: Record<string, string> = ")
        f.write(json.dumps(encoded, separators=(",", ":")))
        f.write(";\n")


if __name__ == "__main__":
    main(sys.argv[1])
