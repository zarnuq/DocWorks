"""Generate src/domain/docx/line-heights.ts: Word's "single" line height for common fonts, as a multiple of the
font size, so documents paginate like Word without the fonts.

Usage: python scripts/make_line_heights.py <fonts-dir>   (needs fonttools)

Word's single line is the font's Windows ascent + descent, plus whatever part of the hhea line gap they don't
already cover. Only real fonts are measured: metric-compatible clones match widths, not heights, so fonts we only
have clones of keep heights measured in Word (MEASURED below).

Font sources (only vertical metrics are read):
  Arial, Times New Roman, Courier New, Verdana, Georgia, Trebuchet, Comic Sans, Arial Black, Impact
                                       nixpkgs#corefonts (NIXPKGS_ALLOW_UNFREE=1)
  Carlito (= Calibri's metrics), Caladea (= Cambria's), Lato, Open Sans
                                       nixpkgs#carlito, #caladea, #lato, #open-sans
Roboto and Montserrat are left out: their versions differ in vertical metrics.
"""
import os
import sys

from fontTools.ttLib import TTFont

FONTS = {
    "arial": "Arial.ttf",
    "times new roman": "Times_New_Roman.ttf",
    "courier new": "Courier_New.ttf",
    "verdana": "Verdana.ttf",
    "georgia": "Georgia.ttf",
    "trebuchet ms": "Trebuchet_MS.ttf",
    "comic sans ms": "Comic_Sans_MS.ttf",
    "arial black": "Arial_Black.ttf",
    "impact": "Impact.ttf",
    "calibri": "Carlito-Regular.ttf",
    "calibri light": "Carlito-Regular.ttf",
    "cambria": "Caladea-Regular.ttf",
    "lato": "Lato-Regular.ttf",
    "open sans": "OpenSans-Regular.ttf",
}

# Measured in Word: fonts we have no file for, or only a clone with other vertical metrics.
MEASURED = {
    "aptos": 1.2, "garamond": 1.33, "segoe ui": 1.33, "tahoma": 1.21, "century gothic": 1.23,
    "book antiqua": 1.17, "palatino linotype": 1.14, "arial narrow": 1.15,
}


def single(path: str) -> float:
    font = TTFont(path, lazy=True)
    os2, hhea = font["OS/2"], font["hhea"]
    win = os2.usWinAscent + os2.usWinDescent
    extra = max(0, hhea.lineGap - (win - (hhea.ascent - hhea.descent)))
    return (win + extra) / font["head"].unitsPerEm


def main() -> None:
    folder = sys.argv[1]
    heights = {family: round(single(os.path.join(folder, file)), 4) for family, file in FONTS.items()}
    heights.update(MEASURED)
    lines = [f'  "{family}": {value},' for family, value in sorted(heights.items())]
    out = os.path.join(os.path.dirname(__file__), "..", "src", "domain", "docx", "line-heights.ts")
    with open(out, "w") as f:
        f.write("// Generated by scripts/make_line_heights.py - do not edit.\n")
        f.write("/** Word's single line height per font family (lower case), as a multiple of the font size. */\n")
        f.write("export const LINE_HEIGHTS: Record<string, number> = {\n" + "\n".join(lines) + "\n};\n")


main()
