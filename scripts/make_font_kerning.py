"""Generate src/presentation/pptx/font-kerning.ts: kerning pairs for the most common Office fonts, so text set
in them is as wide as Word / PowerPoint / Google Docs make it even when the font isn't installed.

Usage: python scripts/make_font_kerning.py <fonts-dir>   (needs fonttools)

Font sources (only pair adjustments are extracted, no font data is shipped):
  Carlito (Calibri's metrics)   github.com/google/fonts  (nixpkgs#carlito)
  Arial, Times New Roman        sourceforge.net/projects/corefonts  (nixpkgs#corefonts)
  Aptos, Aptos Display          download.microsoft.com ("Microsoft Aptos Fonts.zip")
"""
import base64
import json
import os
import sys

from fontTools.ttLib import TTFont

# Pairs among printable ASCII and typographic quotes / dashes.
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "‘’“”–—…"
UNITS = 200  # values stored as int8 in 1/200 em

# family -> files for [regular, bold].
FONTS = {
    "calibri": ["Carlito-Regular.ttf", "Carlito-Bold.ttf"],
    "arial": ["Arial.ttf", "Arial_Bold.ttf"],
    "times new roman": ["Times_New_Roman.ttf", "Times_New_Roman_Bold.ttf"],
    "aptos": ["Aptos.ttf", "Aptos-Bold.ttf"],
    "aptos display": ["Aptos-Display.ttf", "Aptos-Display-Bold.ttf"],
}


def pair_lookups(font):
    """PairPos subtables of the GPOS 'kern' feature, in lookup order."""
    if "GPOS" not in font:
        return []
    gpos = font["GPOS"].table
    indices = sorted({i for fr in gpos.FeatureList.FeatureRecord if fr.FeatureTag == "kern" for i in fr.Feature.LookupListIndex})
    out = []
    for i in indices:
        lookup = gpos.LookupList.Lookup[i]
        for st in lookup.SubTable:
            if lookup.LookupType == 9:
                st = st.ExtSubTable
            if st.LookupType == 2:
                out.append(st)
    return out


def pair_value(subtables, a, b):
    """Advance adjustment for glyph a followed by glyph b: the first subtable covering a that has the pair."""
    for st in subtables:
        if a not in st.Coverage.glyphs:
            continue
        if st.Format == 1:
            pairs = st.PairSet[st.Coverage.glyphs.index(a)].PairValueRecord
            for rec in pairs:
                if rec.SecondGlyph == b:
                    return getattr(rec.Value1, "XAdvance", 0) or 0
        else:
            c1 = st.ClassDef1.classDefs.get(a, 0)
            c2 = st.ClassDef2.classDefs.get(b, 0)
            rec = st.Class1Record[c1].Class2Record[c2]
            return getattr(rec.Value1, "XAdvance", 0) or 0
    return None


def kerning(path):
    font = TTFont(path)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = [cmap.get(ord(c)) for c in CHARS]
    legacy = {}
    if "kern" in font:
        for t in font["kern"].kernTables:
            legacy.update(getattr(t, "kernTable", {}))
    subtables = pair_lookups(font)
    out = bytearray()
    for i, a in enumerate(glyphs):
        for j, b in enumerate(glyphs):
            if not a or not b:
                continue
            v = pair_value(subtables, a, b) if subtables else None
            if v is None:
                v = legacy.get((a, b), 0)
            units = round(v * UNITS / upm)
            if units:
                out += bytes([i, j, units & 0xFF])
    return base64.b64encode(bytes(out)).decode()


def main():
    root = sys.argv[1]
    entries = {name: [kerning(os.path.join(root, f)) for f in files] for name, files in FONTS.items()}
    lines = [
        "// Generated by scripts/make_font_kerning.py - do not edit.",
        "/** Characters the pairs index into. */",
        f"export const KERN_CHARS = {json.dumps(CHARS, ensure_ascii=False)};",
        f"export const KERN_UNITS = {UNITS};",
        "/** family -> base64 [first, second, int8 adjustment] triples for [regular, bold]. */",
        "export const KERNING: Record<string, string[]> = {",
        *[f"  {json.dumps(name)}: {json.dumps(v)}," for name, v in entries.items()],
        "};",
        "",
    ]
    path = os.path.join(os.path.dirname(__file__), "..", "src", "presentation", "pptx", "font-kerning.ts")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    for name, v in entries.items():
        print(name, [len(x) * 3 // 4 // 3 for x in v], "pairs")
    print(os.path.getsize(path), "bytes")


if __name__ == "__main__":
    main()
